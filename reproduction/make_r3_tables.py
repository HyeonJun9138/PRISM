"""Generate the revised prediction tables for the R3 revision (never by hand).

    python make_r3_tables.py        # -> R3_TABLES.md + r3_numbers.json (next to this file)

Sources (all produced by the frozen code; see DECISIONS.md D6):
  model evaluations   Logs/Analysis/eval_r3/<tag>_<set>_report.json
  baselines           Logs/Models/baselines_r3/report_<method>_test_<id|ood>_revised_current_idxcurrent.json
  training summaries  Logs/Models/<job>_<tag>/{job.json, metrics.jsonl}
  recalibration       Paper/rebuttal/r3/recal_r3_k3_s1.json
  rollouts            Paper/rebuttal/r3/rollout_r3_k3_s1_*heldout*.json
Missing inputs are printed as PENDING; nothing is imputed.
"""
from __future__ import annotations

import os

import glob
import json
import os
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__)).replace("\\", "/")
MODELS = (os.environ["PRISM_ROOT"] + '/Logs/Models')
EV = (os.environ["PRISM_ROOT"] + '/Logs/Analysis/eval_r3')
BL = (os.environ["PRISM_ROOT"] + '/Logs/Models/baselines_r3')
SEEDS = [1, 2, 3, 4, 5, 6]            # the six-seed summary (seed 0 pairs the ablations)
NUM = {}


def J(p):
    return json.load(open(p, encoding="utf-8-sig"))


def rep(tag, split):
    p = f"{EV}/{tag}_{split}_report.json"
    return J(p) if os.path.exists(p) else None


def base(method, split):
    p = f"{BL}/report_{method}_test_{split}_revised_current_idxcurrent.json"
    return J(p) if os.path.exists(p) else None


def job(tag):
    js = [j for j in sorted(glob.glob(f"{MODELS}/*_{tag}")) if os.path.exists(j + "/final/model_final.pt")]
    if not js:
        # an interrupted job whose evaluated checkpoint is documented in job_overrides.json (DECISIONS D6.17)
        ov = (J(f"{HERE}/job_overrides.json") if os.path.exists(f"{HERE}/job_overrides.json") else {}).get(tag)
        if ov:
            return {"dir": ov["job"], "best": ov["best"], "val_last": None, "epochs": ov.get("epochs"),
                    "best_metric": ov["best_metric"], "note": ov["note"]}
        return None
    d = js[-1]; jj = J(d + "/job.json")
    vals = [json.loads(l) for l in open(d + "/metrics.jsonl", encoding="utf-8-sig") if '"split": "val"' in l]
    cfg = J(d + "/config.json") if os.path.exists(d + "/config.json") else {}
    return {"dir": os.path.basename(d), "best": jj.get("summary", {}).get("best"), "val_last": vals[-1] if vals else None,
            "epochs": len(vals), "best_metric": (cfg.get("config", cfg).get("checkpoint") or {}).get("best_metric", "val/NLL")}


def f(x, n=2):
    return "PENDING" if x is None else f"{x:.{n}f}"


COLS = [("minADE", 2), ("minFDE", 2), ("top1ADE", 2), ("meanADE", 2), ("NLL", 3), ("trajNLL", 3), ("ES", 1),
        ("cov50_15s", 3), ("cov70_15s", 3), ("cov90_15s", 3), ("cov90_5s", 3)]


def row_vals(o):
    return [o.get(k) if o else None for k, _ in COLS]


out = []; w = out.append
w("# R3 revised prediction tables (generated by make_r3_tables.py; do not edit)\n")
w("All rows use the current-track rule and the current-track sample set (ID 170,076 samples; OOD 399,403), the same "
  "metric code and seeded Monte Carlo (coverage seed 20260925, energy-score seed 20260926). NLL is the position-marginal "
  "mixture NLL in 100 m units; trajNLL is the trajectory-level NLL with the branch shared over the trajectory (Eq. 6); "
  "ES is the energy score of the joint 30-step trajectory [m].\n")

for split, lab in (("testid", "ID"), ("testood", "OOD")):
    bsplit = "id" if split == "testid" else "ood"
    w(f"## Table 7 ({lab}): accuracy and calibration\n")
    w("| method | n | " + " | ".join(k for k, _ in COLS) + " |")
    w("|---|---|" + "---|" * len(COLS))
    for meth, name in (("cv-obs", "CV-obs (LS fit, current-refit sigma)"), ("cv-gt", "CV-gt (information bound)"),
                       ("imm-gapfix", "IMM (init fix, re-tuned)")):
        b = base(meth, bsplit)
        o = b["overall"] if b else None
        w(f"| {name} | {b['n_samples'] if b else 'PENDING'} | " + " | ".join(f(v, n) for v, (k, n) in zip(row_vals(o), COLS)) + " |")
        if o:
            for k, _ in COLS:
                NUM[f"r3.{lab}.{meth}.{k}"] = o.get(k)
    for tag, name in (("r3_pointnet_s0", "Point-MSE (K=1, seed 0)"), ("r3_k1_s0", "K=1 NLL (seed 0)"),
                      ("r3_mdn_s0", "Transformer-MDN (seed 0)"), ("r3_k3_s0", "PRISM K=3 (seed 0)")):
        r = rep(tag, split); o = r["overall"] if r else None
        w(f"| {name} | {r['n_samples'] if r else 'PENDING'} | " + " | ".join(f(v, n) for v, (k, n) in zip(row_vals(o), COLS)) + " |")
        if o:
            for k, _ in COLS:
                NUM[f"r3.{lab}.{tag}.{k}"] = o.get(k)
    # optional extra seeds of the Transformer-MDN comparator (row appears once >= 2 seeds are evaluated)
    mdn = {s: rep(f"r3_mdn_s{s}", split) for s in (0, 1, 2)}
    hv = [s for s in mdn if mdn[s]]
    if len(hv) >= 2:
        cells = []
        for k, n in COLS:
            v = [mdn[s]["overall"][k] for s in hv]
            m, sd = st.mean(v), st.stdev(v); cells.append(f"{m:.{n}f} ± {sd:.{n}f}")
            NUM[f"r3.{lab}.mdn_seeds.{k}.mean"] = m; NUM[f"r3.{lab}.mdn_seeds.{k}.sd"] = sd
        NUM[f"r3.{lab}.mdn_seeds.n"] = len(hv)
        w(f"| Transformer-MDN, seeds {','.join(map(str, hv))} (mean ± s.d.) | {mdn[hv[0]]['n_samples']} | " + " | ".join(cells) + " |")
    # six-seed summary
    got = {s: rep(f"r3_k3_s{s}", split) for s in SEEDS}
    have = [s for s in SEEDS if got[s]]
    cells = []
    for k, n in COLS:
        v = [got[s]["overall"][k] for s in have]
        if len(v) >= 2:
            m, sd = st.mean(v), st.stdev(v); cells.append(f"{m:.{n}f} ± {sd:.{n}f}")
            NUM[f"r3.{lab}.prism_seeds.{k}.mean"] = m; NUM[f"r3.{lab}.prism_seeds.{k}.sd"] = sd
        else:
            cells.append("PENDING")
    NUM[f"r3.{lab}.prism_seeds.n"] = len(have)
    w(f"| **PRISM K=3, seeds {','.join(map(str, have))} (mean ± s.d.)**{'' if len(have) == len(SEEDS) else ' [PENDING seeds ' + ','.join(str(s) for s in SEEDS if s not in have) + ']'} | "
      f"{got[have[0]]['n_samples'] if have else 'PENDING'} | " + " | ".join(cells) + " |")
    r = rep("s4", f"{split}_indexcurrent"); o = r["overall"] if r else None
    w(f"| Oracle association (submitted model, slot inputs) | {r['n_samples'] if r else 'PENDING'} | " + " | ".join(f(v, n) for v, (k, n) in zip(row_vals(o), COLS)) + " |")
    if o:
        for k, _ in COLS:
            NUM[f"r3.{lab}.oracle_s4.{k}"] = o.get(k)
    w("")
    w("Point-MSE (loss variant `mse`) is trained by squared error on μ only; its σ, ρ and π heads receive no gradient, "
      "so its NLL, trajNLL, ES and coverage columns score an untrained spread head (the submitted Table 7 reported "
      "them the same way). Its accuracy columns are the comparable ones." + chr(10))
    w(f"Per-seed ({lab}):\n")
    w("| seed | minADE | NLL | trajNLL | ES | cov90@15 s | job |")
    w("|---|---|---|---|---|---|---|")
    for s in [0] + SEEDS:
        r = rep(f"r3_k3_s{s}", split); jb = job(f"r3_k3_s{s}")
        o = r["overall"] if r else {}
        w(f"| {s} | {f(o.get('minADE'))} | {f(o.get('NLL'), 4)} | {f(o.get('trajNLL'), 4)} | {f(o.get('ES'), 1)} | {f(o.get('cov90_15s'), 4)} | {jb['dir'] if jb else 'PENDING'} |")
    w("")

# ------------------------------------------------------------- reacquisition
for split, lab in (("testid", "ID"), ("testood", "OOD")):
    w(f"## Reacquisition strata ({lab}, current-track samples)\n")
    w("| model | reacq 0 n | minADE | NLL | reacq 1 n | minADE | NLL |")
    w("|---|---|---|---|---|---|---|")
    for tag, name in [("s4", "oracle (submitted)")] + [(f"r3_k3_s{s}", f"PRISM seed {s}") for s in [0] + SEEDS]:
        r = rep(tag, f"{split}_indexcurrent" if tag == "s4" else split)
        if not r:
            w(f"| {name} | PENDING |  |  |  |  |  |"); continue
        S = r["strata"]["reacq"]
        a, b = S.get("0", {}), S.get("1", {})
        w(f"| {name} | {a.get('n')} | {f(a.get('minADE'))} | {f(a.get('NLL'), 3)} | {b.get('n')} | {f(b.get('minADE'))} | {f(b.get('NLL'), 3)} |")
    w("")

# ------------------------------------------------------------- ablations
w("## Table 10: ablations (all seed 0, current-track rule)\n")
w("| model | kept checkpoint: selection metric = value (epoch) | ID minADE | ID NLL | ID cov90@15 s | OOD minADE | OOD NLL | OOD cov90@15 s |")
w("|---|---|---|---|---|---|---|---|")
for tag, name in (("r3_k3_s0", "full (K=3)"), ("r3_k1_s0", "K=1"), ("r3_noneigh_s0", "no neighbours"),
                  ("r3_notype_s0", "no type head"), ("r3_mdn_s0", "standard MDN training"), ("r3_pointnet_s0", "Point-MSE"),
                  ("r3_1x_s0", "full (K=3), 1x corpus (data scale)")):
    jb = job(tag); ri, ro = rep(tag, "testid"), rep(tag, "testood")
    bv = (f"{jb['best_metric']} = {jb['best']['value']:.4f} ({jb['best']['epoch']})" if jb and jb.get("best") else "PENDING")
    if tag == "r3_1x_s0" and jb and jb.get("best"):
        bv += " †"
    if jb and jb.get("note"):
        bv += " ‡"
    oi, oo = (ri or {}).get("overall", {}), (ro or {}).get("overall", {})
    w(f"| {name} | {bv} | {f(oi.get('minADE'))} | {f(oi.get('NLL'), 3)} | {f(oi.get('cov90_15s'), 3)} | {f(oo.get('minADE'))} | {f(oo.get('NLL'), 3)} | {f(oo.get('cov90_15s'), 3)} |")
    if jb and jb.get("best"):
        NUM[f"r3.ablation.{tag}.val_best"] = jb["best"]["value"]
    for sp, o in (("testid", oi), ("testood", oo)):
        for k in ("minADE", "NLL", "cov90_15s"):
            if o.get(k) is not None:
                NUM[f"r3.ablation.{tag}.{sp}.{k}"] = o[k]
w("")
w("† 1x 코퍼스 모델은 제출본 1x 모델과 같은 설정으로, 1x 검증셋(20260812_203525_valid_full)의 val/minADE로 체크포인트를 "
  "골랐다. 검증 값은 5x 모델과 비교할 수 없다. Point-MSE도 val/minADE로 골랐다(σ 헤드 미학습). "
  "‡ Point-MSE 학습은 26번째 에폭 검증 중 러너 회수로 중단됐다. 에폭 26을 같은 스냅숏으로 재개해 확인했으나 "
  "최적(에폭 21)을 넘지 못했으므로, 중단이 없었을 때와 같은 에폭 21 체크포인트를 평가했다(job_overrides.json, D6.17). "
  "시험 열(ID/OOD)은 모든 행이 같은 현재 트랙 표본이다." + chr(10))

# ------------------------------------------------------------- Table 9 (revised): per-class accuracy, calibration, class recovery (seed 1)
import numpy as np
TYPE_NAMES = ["Bird", "Multirotor", "FixedWingUAS", "eVTOL", "GA", "Debris", "Unknown"]   # modelTraining/common/constants.py order
TRAINED = (1, 2, 3)
w("## Table 9 (revised): per-class accuracy, calibration and class recovery (planner model seed 1, current-track sets)" + chr(10))
w("Class recovery = share of the class's samples whose predicted class (argmax of the type head) equals the true class (ID) or, for classes "
  "absent from training (OOD), the trained class they are most often assigned to. cov90@15 s = share of samples whose true 15 s "
  "position lies inside the 90 % HPD region. Baseline minADE per class from the revised current-track baseline reports (same samples)." + chr(10))
for split, lab in (("testid", "ID"), ("testood", "OOD")):
    pp = f"{EV}/r3_k3_s1_{split}_persample.npz"
    if not os.path.exists(pp):
        w(f"{lab}: PENDING (no per-sample file)" + chr(10)); continue
    z = np.load(pp, allow_pickle=True)
    tl, tp = z["type_label"].astype(int), z["type_pred"].astype(int)
    made, nll, c90 = z["minADE"].astype(float), z["NLL"].astype(float), z["cov"][:, 2, 2].astype(float)
    bt = {m: (base(m, "id" if split == "testid" else "ood") or {}).get("by_type", {}) for m in ("cv-obs", "cv-gt", "imm-gapfix")}
    w(f"{lab} (n = {len(tl):,}):" + chr(10))
    w("| class | trained | n | share | PRISM minADE | PRISM NLL | cov90@15 s | class recovery | CV-obs minADE | CV-gt minADE | IMM minADE |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for ci, name in enumerate(TYPE_NAMES):
        m = tl == ci
        if not m.any():
            continue
        n = int(m.sum()); preds = np.bincount(tp[m], minlength=len(TYPE_NAMES)) / n
        if ci in TRAINED:
            rec = f"{preds[ci]:.3f} as itself"
        else:
            j = int(np.argmax(preds)); rec = f"{preds[j]:.2f} as {TYPE_NAMES[j]}"
        b = lambda meth: f(bt[meth].get(name, {}).get("minADE"))
        w(f"| {name} | {'yes' if ci in TRAINED else 'no'} | {n} | {n / len(tl):.3f} | {made[m].mean():.2f} | {nll[m].mean():.3f} | "
          f"{c90[m].mean():.3f} | {rec} | {b('cv-obs')} | {b('cv-gt')} | {b('imm-gapfix')} |")
        NUM[f"r3.{lab}.class.{name}.n"] = n
        NUM[f"r3.{lab}.class.{name}.minADE"] = float(made[m].mean()); NUM[f"r3.{lab}.class.{name}.NLL"] = float(nll[m].mean())
        NUM[f"r3.{lab}.class.{name}.cov90_15s"] = float(c90[m].mean())
        NUM[f"r3.{lab}.class.{name}.pred_as"] = {TYPE_NAMES[k]: round(float(v), 4) for k, v in enumerate(preds) if v > 0}
        for meth in ("cv-obs", "cv-gt", "imm-gapfix"):
            if name in bt[meth]:
                NUM[f"r3.{lab}.class.{name}.{meth}.minADE"] = bt[meth][name]["minADE"]
    acc = float((tl == tp).mean()); NUM[f"r3.{lab}.type_acc_persample"] = acc
    w(chr(10) + f"Overall class accuracy {acc:.3f} (argmax over all seven classes; trained classes only appear in the ID set)." + chr(10))

# ------------------------------------------------------------- factor-wise OOD and parameter sensitivity (seed 1)
w("## Factor-wise OOD (R2-III), planner model seed 1\n")
w("| set | n | minADE | NLL | cov90@15 s | type acc |")
w("|---|---|---|---|---|---|")
for fct in ("control", "density", "wind", "intent", "platform", "all"):
    r = rep("r3_k3_s1", f"factor_{fct}"); o = (r or {}).get("overall", {})
    w(f"| {fct} | {r['n_samples'] if r else 'PENDING'} | {f(o.get('minADE'))} | {f(o.get('NLL'), 3)} | {f(o.get('cov90_15s'), 3)} | {f(o.get('type_acc'), 3)} |")
    for k in ("minADE", "NLL", "cov90_15s", "type_acc"):
        if o: NUM[f"r3.factor.{fct}.{k}"] = o.get(k)
w("")
w("## Parameter sensitivity (R2-II), planner model seed 1\n")
w("| set | n | minADE | NLL | cov90@15 s |")
w("|---|---|---|---|---|")
for sn in ("baseline", "dwell_hi", "dwell_lo", "notice_hi", "notice_lo", "sensor_2x"):
    r = rep("r3_k3_s1", f"sens_{sn}"); o = (r or {}).get("overall", {})
    w(f"| {sn} | {r['n_samples'] if r else 'PENDING'} | {f(o.get('minADE'))} | {f(o.get('NLL'), 3)} | {f(o.get('cov90_15s'), 3)} |")
    for k in ("minADE", "NLL", "cov90_15s"):
        if o: NUM[f"r3.sens.{sn}.{k}"] = o.get(k)
w("")

# ------------------------------------------------------------- recalibration and rollouts (seed 1)
w("## Recalibration (M2) and rollout diagnostics (M1), planner model seed 1\n")
rc = J(f"{HERE}/recal_r3_k3_s1.json")
w(f"T = {rc['T']} fitted on {rc['n_cal']} samples; held-out {rc['n_test']} samples (test_ood episodes 300-1199, seed overlap {rc['seed_overlap']['n_overlap']}).\n")
w("| | NLL | cov50@15 | cov70@15 | cov90@15 | cov90@5 |")
w("|---|---|---|---|---|---|")
for k in ("before", "after"):
    x = rc[k]; w(f"| {k} | {x.get('NLL')} | {x.get('cov50_15s')} | {x.get('cov70_15s')} | {x.get('cov90_15s')} | {x.get('cov90_5s')} |")
    for kk in ("NLL", "cov90_15s", "cov50_15s"):
        NUM[f"r3.recal.{k}.{kk}"] = x.get(kk)
NUM["r3.recal.T"] = rc["T"]
w("\nTransfer of the same T:\n")
w("| factor set | cov90@15 before → after | NLL before → after |")
w("|---|---|---|")
for k, v in rc["transfer"].items():
    if isinstance(v, dict) and "before" in v:
        w(f"| {k} | {v['before'].get('cov90_15s')} → {v['after'].get('cov90_15s')} | {v['before'].get('NLL')} → {v['after'].get('NLL')} |")
w("")
w("| rollout set | scale | cov50/70/90 @5 s | @10 s | @15 s | groups |")
w("|---|---|---|---|---|---|")
for fn, lab, T in (("rollout_r3_k3_s1_idheldout_T1", "ID held-out", 1), ("rollout_r3_k3_s1_oodheldout_T1", "OOD held-out", 1),
                   ("rollout_r3_k3_s1_oodheldout_T1695", "OOD held-out", 1.695)):
    d = J(f"{HERE}/{fn}.json"); g = d["bootstrap"]["group"]["conditional_coverage"]
    cell = lambda h: "/".join(f"{g[h][n]['mean']:.3f}" for n in ("nom50", "nom70", "nom90"))
    w(f"| {lab} | {T} | {cell('5s')} | {cell('10s')} | {cell('15s')} | {d['bootstrap']['group']['n_units']} |")
    NUM[f"r3.rollout.{fn}.cov90_15s"] = g["15s"]["nom90"]["mean"]
w("")

open(f"{HERE}/R3_TABLES.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
json.dump(NUM, open(f"{HERE}/r3_numbers.json", "w", encoding="utf-8"), indent=1)
print("written R3_TABLES.md", len(out), "lines;", len(NUM), "numbers")
